import * as fs from 'fs';
import * as path from 'path';

import { ProjectStatus } from 'src/projects/enums/project-status.enum';
import { TeamStatus } from 'src/teams/enums/team-status.enum';

import {
  COMPANY,
  HISTORY_START,
  SEED_PASSWORD,
  TEAMS,
  PROJECTS,
  USERS,
} from './seed-config';

const TARGET = path.resolve(__dirname, '../../docs/TEST-CREDENTIALS.md');

export function writeCredentialsFile(): string {
  const rows = USERS.map(
    (user) =>
      `| ${user.role} | \`${user.email}\` | ${user.firstName} ${user.lastName} | ${user.note ?? ''} |`,
  ).join('\n');

  const teams = TEAMS.map((team) => {
    const heading =
      team.status === TeamStatus.ARCHIVED
        ? `### ${team.name} (archived, former members)`
        : `### ${team.name}`;
    const members = team.members
      .map((member) => `- ${member.email} (${member.roleInTeam})`)
      .join('\n');

    return `${heading}\n\n${members}`;
  }).join('\n\n');

  const projects = PROJECTS.map((project) => {
    const name =
      project.status === ProjectStatus.ARCHIVED
        ? `**${project.name}** (archived)`
        : `**${project.name}**`;

    return `- ${name} — ${project.members.join(', ') || 'nobody'}`;
  }).join('\n');

  const content = `# Test logins

Generated by \`make seed\`. Do not edit by hand — change
\`apps/backend/src/seed/seed-config.ts\` and re-seed instead.

**Every account below uses the same password:**

\`\`\`
${SEED_PASSWORD}
\`\`\`

Sign in at http://localhost:3000/login

## Accounts

All of them belong to the single test company **${COMPANY.companyName}**.

| Role | Email | Name | What it is for |
| :--- | :--- | :--- | :--- |
${rows}

Deactivated accounts cannot sign in.

## Teams

${teams}

A manager sees only the people in the teams they lead: anyone else is invisible
to them — that is deliberate, and it is how you check the role-visibility rules
by hand.

## Project members

${projects}

## Reports history

Time, plans and absences from ${HISTORY_START} up to yesterday, so Reports have
July to the current month to show; the company starts in June, which is empty.
What each person logs and plans is \`REPORT_HISTORY\` in the seed config. Sign
in as the owner for the whole company, or as Sarah Manager for her two teams.

> This file contains a password, so it is not committed: the repository ignores
> \`*.md\` by default. Re-run \`make seed\` to recreate it.
`;

  // Everything in docs/ is gitignored, so a fresh clone has no such folder.
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, content, 'utf8');

  return TARGET;
}
